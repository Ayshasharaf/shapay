
-- 1. Simulated payments
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount DECIMAL(10, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Merchant destinations
CREATE TABLE webhook_endpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(2048) NOT NULL,
    secret_key VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Events each endpoint subscribes to
CREATE TABLE webhook_endpoint_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,

    CONSTRAINT fk_endpoint_events_endpoint
        FOREIGN KEY (endpoint_id)
        REFERENCES webhook_endpoints(id),

    CONSTRAINT uq_endpoint_event
        UNIQUE (endpoint_id, event_type)
);

-- 4. Events generated by ShaPay
CREATE TABLE webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    payment_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_webhook_events_payment
        FOREIGN KEY (payment_id)
        REFERENCES payments(id)
);

-- 5. Individual delivery jobs for each endpoint
CREATE TABLE webhook_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    webhook_event_id BIGINT NOT NULL,
    endpoint_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP,
    claimed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_deliveries_event
        FOREIGN KEY (webhook_event_id)
        REFERENCES webhook_events(id),

    CONSTRAINT fk_deliveries_endpoint
        FOREIGN KEY (endpoint_id)
        REFERENCES webhook_endpoints(id),

    CONSTRAINT uq_event_endpoint
        UNIQUE (webhook_event_id, endpoint_id)
);

-- 6. History of individual HTTP delivery attempts
CREATE TABLE delivery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL,
    attempt_number INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    response_code INT,
    response_body TEXT,
    duration_ms BIGINT,
    attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attempts_delivery
        FOREIGN KEY (delivery_id)
        REFERENCES webhook_deliveries(id),

    CONSTRAINT uq_delivery_attempt
        UNIQUE (delivery_id, attempt_number)
);

-- Indexes
CREATE INDEX idx_deliveries_status_next_attempt
    ON webhook_deliveries(status, next_attempt_at);

CREATE INDEX idx_deliveries_endpoint
    ON webhook_deliveries(endpoint_id);

CREATE INDEX idx_webhook_events_payment
    ON webhook_events(payment_id);

CREATE INDEX idx_delivery_attempts_delivery
    ON delivery_attempts(delivery_id);

CREATE INDEX idx_endpoint_events_type
    ON webhook_endpoint_events(event_type);
